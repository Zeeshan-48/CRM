// Reused across responses: every endpoint answers in the CRM's envelope.
const envelope = (dataSchema: Record<string, unknown>) => ({
  type: "object",
  required: ["success", "data"],
  properties: {
    success: { type: "boolean", const: true },
    data: dataSchema,
    message: { type: "string" },
    statusCode: { type: "integer" },
  },
});

