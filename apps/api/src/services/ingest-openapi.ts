/**
 * OpenAPI description of the public integration surface (everything under
 * `/api/v1/ingest`).
 *
 * Hand-authored rather than generated, and deliberately so: the request bodies
 * here are intentionally permissive (a producer may send `full_name` or
 * `first_name`/`last_name`; a price may be a number or a numeric string), and the
 * zod schemas that guard them are loose on purpose so that
 * `services/catalog-mapping` can return the field-level guidance that actually
 * makes an integration debuggable. Generating from those schemas would document
 * "products: array of unknown", which tells an integrator nothing.
 *
 * Served from the API itself (`GET /ingest/openapi.json`) so a team pointing
 * their client generator at a deployment always gets that deployment's contract,
 * and so the spec cannot be published to a docs site and quietly rot there.
 *
 * When an endpoint's behaviour changes, this file changes with it. It is the
 * integration contract, and a wrong spec costs an integrating team more time than
 * no spec at all.
 */

