/**
 * READ-ONLY. Reads information_schema from the dev database and emits the DDL
 * subset the mock database needs, as tests/mock-schema.ts.
 * Regenerate after a schema change:  npx tsx scripts/gen-mock-schema.ts
 */
import "dotenv/config";
import fs from "fs";
import { Pool } from "pg";

const TABLES = [
  // CRM core the product-integration code reads or writes
  "tenants", "users", "leads", "contacts", "deals", "pipelines", "stages",
  "activities", "messages", "api_keys", "audit_logs", "notifications",
  "workflows", "automation_runs", "tenant_entitlements", "webhooks",
  // Product integration platform
  "connected_apps", "products", "product_prices", "product_offers",
  "app_event_definitions", "app_identities", "engagement_profiles",
  "deal_line_items", "webhook_deliveries", "activity_events",
];

const pool = new Pool({ connectionString: process.env.DATABASE_URL, max: 2 });

// pg-mem has no user-defined enum support worth relying on, and Kysely passes
// enum values as plain strings anyway, so enums become TEXT in the mock.
const mapType = (dataType: string, udt: string): string => {
  switch (dataType) {
    case "USER-DEFINED": return "TEXT"; // enum
    case "character varying": return "TEXT";
    case "text": return "TEXT";
    case "integer": return "INTEGER";
    case "bigint": return "BIGINT";
    case "boolean": return "BOOLEAN";
    case "jsonb": case "json": return "JSONB";
    case "timestamp without time zone": case "timestamp with time zone": return "TIMESTAMP";
    case "date": return "DATE";
    case "numeric": case "double precision": case "real": return "NUMERIC";
    default:
      console.warn(`  ! unmapped type ${dataType}/${udt} -> TEXT`);
      return "TEXT";
  }
};

(async () => {
  const out: string[] = [];

  for (const table of TABLES) {
    const cols = (await pool.query(
      `SELECT column_name, data_type, udt_name, is_nullable, column_default
         FROM information_schema.columns
        WHERE table_schema='public' AND table_name=$1
        ORDER BY ordinal_position`, [table]
    )).rows;
    if (!cols.length) { console.warn(`  ! table ${table} not found, skipping`); continue; }

    const pk = (await pool.query(
      `SELECT a.attname FROM pg_index i
         JOIN pg_attribute a ON a.attrelid=i.indrelid AND a.attnum = ANY(i.indkey)
        WHERE i.indrelid=$1::regclass AND i.indisprimary`, [table]
    )).rows.map(r => r.attname);

    const defs = cols.map((c) => {
      const type = mapType(c.data_type, c.udt_name);
      let def = `  "${c.column_name}" ${type}`;
      if (c.is_nullable === "NO") def += " NOT NULL";
      // Keep only literal defaults; function defaults (now(), gen_random_uuid)
      // are applied by the app in this codebase, never by the database.
      const d: string | null = c.column_default;
      if (d && !/\(|nextval|now|CURRENT/i.test(d)) {
        const clean = d.replace(/::[a-zA-Z_ "]+$/, "");
        def += ` DEFAULT ${clean}`;
      }
      return def;
    });
    if (pk.length) defs.push(`  PRIMARY KEY (${pk.map((p) => `"${p}"`).join(", ")})`);

    out.push(`CREATE TABLE "${table}" (\n${defs.join(",\n")}\n);`);

    // Unique indexes only. Non-unique ones are pure performance and pg-mem does
    // not need them; unique ones carry BEHAVIOUR the code relies on (onConflict).
    const idx = (await pool.query(
      `SELECT indexname, indexdef FROM pg_indexes
        WHERE schemaname='public' AND tablename=$1 AND indexdef LIKE '%UNIQUE%'`, [table]
    )).rows;
    for (const i of idx) {
      if (i.indexdef.includes(" WHERE ")) { console.warn(`  ! partial index skipped: ${i.indexname}`); continue; }
      if (pk.length && i.indexname.endsWith("_pkey")) continue;
      out.push(`${i.indexdef.replace(" USING btree", "")};`);
    }
  }

  const body = `// GENERATED by scripts/gen-mock-schema.ts from the dev database schema.
// Do not edit by hand. Regenerate after a schema change:
//   npx tsx scripts/gen-mock-schema.ts
//
// Notes on fidelity:
//  - Postgres enums become TEXT. Kysely sends enum values as strings, so query
//    behaviour is identical, but the mock will NOT reject an invalid enum value.
//  - Only UNIQUE indexes are carried over: those change behaviour (onConflict).
//    Plain performance indexes are irrelevant in memory.
//  - Foreign keys are omitted. The mock is for logic, not referential integrity.

export const MOCK_SCHEMA_SQL = \`
${out.join("\n\n").replace(/`/g, "\\`").replace(/\$\{/g, "\\${")}
\`;
`;
  fs.writeFileSync("tests/mock-schema.ts", body);
  console.log(`wrote tests/mock-schema.ts (${out.length} statements, ${body.length} bytes)`);
  await pool.end();
})().catch((e) => { console.error(e.message); process.exit(1); });
